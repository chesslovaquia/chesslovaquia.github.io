import { logger } from './Logger';

import { w3HideMenu } from './utils';

import { Clvq } from './Clvq';

declare global {
	interface Window {
		Clvq: Clvq;
	}
}

logger.debug('This site was generated by Hugo.');

// Initialize when DOM is loaded
document.addEventListener('DOMContentLoaded', () => {
	logger.debug('Welcome to Chesslovaquia.');
	window.Clvq = new Clvq();
	window.Clvq.lichessFetchPlaying()
		.catch((err: unknown) => { logger.error('Failed to fetch playing games:', err); });
});

window.addEventListener('pageshow', () => {
	w3HideMenu('mainSidebar');
});
